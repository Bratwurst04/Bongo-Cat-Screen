"""Six small 4bpp LVGL glyphs, derived from the installed Montserrat bitmap.

No font converter/runtime dependency. ASCII and symbols fall back unchanged
to their original LVGL font. Only the new header is generated.
"""
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
import export_ui_visuals as v

CHARS = 'ÄÅÖäåö'


def glyphs(size):
    face = v.lvgl_ascii_font('montserrat_' + str(size))
    bitmap, descriptors = [], [(0, 0, 0, 0, 0, 0)]
    for char, base in zip(CHARS, 'AAOaao'):
        g = face['glyphs'][ord(base) - 31]
        width, height = g['box_w'], g['box_h']
        pixels = [0] * (width * 3)
        for i in range(width * height):
            byte = face['bitmap'][g['bitmap_index'] + i // 2]
            pixels.append((byte >> (4 if i % 2 == 0 else 0)) & 15)
        if char in 'Åå':
            cx = width // 2
            for x, y in ((cx, 0), (cx - 1, 1), (cx + 1, 1), (cx, 2)):
                pixels[y * width + x] = 15
        else:
            for left in (max(0, width // 3 - 1), min(width - 2, 2 * width // 3)):
                for x in (left, left + 1):
                    for y in (0, 1): pixels[y * width + x] = 15
        offset = len(bitmap)
        bitmap.extend((pixels[i] << 4) | (pixels[i + 1] if i + 1 < len(pixels) else 0)
                      for i in range(0, len(pixels), 2))
        descriptors.append((offset, g['adv_w'], width, height + 3, g['ofs_x'], g['ofs_y']))
        assert height + 3 + g['ofs_y'] <= face['height'] - face['baseline'], char
    return bitmap, descriptors


def generate():
    parts = ['#pragma once', '// Generated by tools/generate_media_swedish_font.py; six glyphs only.',
             '// Uses the original Montserrat 14/16 bitmaps/metrics plus a 3px diacritic.',
             '// LVGL 8.3.11 bitmap layout, unchanged baseline/line-height and ASCII fallback.',
             'static const uint16_t media_swedish_unicode[] = {0, 1, 18, 32, 33, 50};']
    for size in (14, 16):
        bitmap, ds = glyphs(size)
        p = 'media_swedish_' + str(size)
        parts += [f'static const uint8_t {p}_bitmap[] = {{']
        parts += ['    ' + ', '.join(f'0x{b:02x}' for b in bitmap[i:i + 16]) + ','
                  for i in range(0, len(bitmap), 16)]
        parts += ['};', f'static const lv_font_fmt_txt_glyph_dsc_t {p}_glyphs[] = {{']
        parts += ['    {' + ', '.join(map(str, d)) + '},' for d in ds]
        parts += ['};', f'static const lv_font_fmt_txt_cmap_t {p}_cmap[] = {{',
                  '    {0x00c4, 51, 1, media_swedish_unicode, nullptr, 6, LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}',
                  '};', f'static lv_font_fmt_txt_glyph_cache_t {p}_cache;',
                  f'static const lv_font_fmt_txt_dsc_t {p}_dsc = {{',
                  f'    {p}_bitmap, {p}_glyphs, {p}_cmap, nullptr, 0, 1, 4, 0, 0, &{p}_cache', '};']
    parts += ['inline lv_font_t mediaSwedishFont(const lv_font_t &base, const lv_font_fmt_txt_dsc_t *data) {',
              '    lv_font_t font = base;', '    font.dsc = data;', '    font.fallback = &base;',
              '    return font;', '}',
              'static const lv_font_t lv_font_media_swedish_14 = mediaSwedishFont(lv_font_montserrat_14, &media_swedish_14_dsc);',
              'static const lv_font_t lv_font_media_swedish_16 = mediaSwedishFont(lv_font_montserrat_16, &media_swedish_16_dsc);']
    return '\n'.join(parts) + '\n'


if __name__ == '__main__':
    path = v.ROOT / 'src/media_swedish_font.h'
    path.write_text(generate(), encoding='utf-8')
    print(path.name, path.stat().st_size, 'source bytes')
